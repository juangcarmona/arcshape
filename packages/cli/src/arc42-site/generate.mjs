#!/usr/bin/env node
/**
 * generate.mjs — arc42 snapshot generator (portable, bundled with the architecture-docs skill).
 *
 * Usage:
 *   node generate.mjs <docsDir> [--out <file>] [--title <name>] [--source-ref <ref>] [--site-base </path/>]
 *
 * Reads an arc42 documentation folder (README.md + twelve NN-slug section
 * directories, or the legacy flat NN-*.md layout) with the
 * architecture-docs skill's frontmatter contract and writes exactly one
 * self-contained HTML file: inline styles, inline pre-rendered Mermaid SVGs,
 * inert JSON data, one ES5 router. No external resources; opens from file://.
 * Generation is deterministic and never modifies authored files.
 *
 * Default output: <docsDir>/../arc42-snapshot.html  (sibling of the docs folder)
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { createHash } from "node:crypto";
import { resolve, join, dirname, relative, sep } from "node:path";
import { loadDocs, Diagnostic } from "./loadDocs.mjs";
import {
  renderMarkdown,
  extractMermaidSources,
  extractNativeSources,
  renderMermaid,
} from "./render.mjs";
import { prepareDiagrams } from "./prepare-diagrams.mjs";
import { checkPreview } from "./native-previews.mjs";
import { buildSnapshotHtml } from "./shell.mjs";
import {
  parseNativeDiagram,
  renderNativeDiagrams,
} from "./native-diagrams.mjs";
import { nativeFigure, buildNativeViewer } from "./native-viewer.mjs";
import {
  checkPublicationTarget,
  publishDirectory,
} from "./publish-directory.mjs";

const run = promisify(execFile);
const generatedMarker =
  "<!-- Generated by ArcShape from canonical Markdown. -->";

function usage(code = 1) {
  process.stdout.write(
    [
      "Usage: node generate.mjs <docsDir> [--out <file>] [--title <name>] [--source-ref <ref>] [--site-base </path/>]",
      "",
      "  docsDir   folder containing README.md and twelve arc42 section directories",
      "  --out     output HTML path (default: <docsDir>/../arc42-snapshot.html)",
      "  --title   page title override (default: derived from docsDir parent folder)",
      "  --source-ref  Git branch, tag, or ref for repository source links (default: current branch)",
      "",
    ].join("\n"),
  );
  process.exit(code);
}

function parseArgs(argv) {
  const positional = [];
  const flags = {};
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (
      arg === "--format" ||
      arg === "--archify-deep-dives" ||
      arg === "--diagram-engine" ||
      arg === "--out" ||
      arg === "--title" ||
      arg === "--source-ref" ||
      arg === "--site-base"
    ) {
      if (!argv[i + 1] || argv[i + 1].startsWith("--")) usage(1);
      flags[arg.slice(2)] = argv[i + 1];
      i += 1;
    } else if (arg === "--help" || arg === "-h") {
      usage(0);
    } else if (arg.startsWith("-")) {
      usage(1);
    } else {
      positional.push(arg);
    }
  }
  const siteBase = flags["site-base"] ?? "/";
  if (!siteBase.startsWith("/") || !siteBase.endsWith("/"))
    throw new Error("--site-base must start and end with a slash");
  return { positional, flags };
}

/** Best-effort git revision of the repository containing docsDir. */
async function gitRevision(docsDir) {
  try {
    const { stdout } = await run("git", ["rev-parse", "HEAD"], {
      cwd: docsDir,
    });
    return stdout.trim();
  } catch {
    return undefined;
  }
}

async function gitSourceContext(docsDir, sourceRefOverride) {
  try {
    const [root, remote, ref] = await Promise.all([
      run("git", ["rev-parse", "--show-toplevel"], { cwd: docsDir }),
      run("git", ["remote", "get-url", "origin"], { cwd: docsDir }),
      run("git", ["branch", "--show-current"], { cwd: docsDir }),
    ]);
    const repositoryUrl = githubRepositoryUrl(remote.stdout.trim());
    return repositoryUrl
      ? {
          root: root.stdout.trim(),
          repositoryUrl,
          ref: sourceRefOverride || ref.stdout.trim() || "HEAD",
        }
      : undefined;
  } catch {
    return undefined;
  }
}

function githubRepositoryUrl(remote) {
  const match =
    /^(?:https:\/\/github\.com\/|git@github\.com:)([^/]+\/[^/]+?)(?:\.git)?$/.exec(
      remote,
    );
  return match ? `https://github.com/${match[1]}` : undefined;
}

async function main() {
  const { positional, flags } = parseArgs(process.argv.slice(2));
  if (positional.length !== 1) usage(1);
  const docsDir = resolve(positional[0]);
  const format = flags.format ?? "snapshot";
  if (!["snapshot", "interactive"].includes(format))
    throw new Diagnostic("--format must be snapshot or interactive");
  const interactive = format === "interactive";
  const deepDiveMode = flags["archify-deep-dives"] ?? "auto";
  if (!["auto", "off"].includes(deepDiveMode))
    throw new Diagnostic("--archify-deep-dives must be auto or off");
  const diagramEngine =
    flags["diagram-engine"] ?? (deepDiveMode === "off" ? "mermaid" : "auto");
  if (!["auto", "mermaid"].includes(diagramEngine))
    throw new Diagnostic("--diagram-engine must be auto or mermaid");

  let docs;
  try {
    docs = await loadDocs(docsDir);
  } catch (error) {
    if (error instanceof Diagnostic) {
      process.stderr.write(`arc42-snapshot: ${error.message}\n`);
      process.exit(2);
    }
    throw error;
  }

  const stackName = flags.title ?? docs.stackName;
  const outFile = flags.out
    ? resolve(flags.out)
    : join(
        dirname(docsDir),
        interactive ? "arc42-interactive" : "arc42-snapshot.html",
      );
  if (interactive) await checkPublicationTarget(outFile, docsDir);
  if (!interactive && !/\.html?$/i.test(outFile)) {
    throw new Diagnostic(
      "--out must name an .html or .htm file; authored Markdown is never an output target",
    );
  }

  // Route map: every authored Markdown file gets a stable reader route.
  const fileToRoute = new Map([[docs.readme.file, "#/"]]);
  for (const section of docs.sections) {
    fileToRoute.set(section.file, `#/section/${section.number}`);
    for (const supporting of section.supporting)
      fileToRoute.set(supporting.file, supporting.route);
  }

  // Pre-render every mermaid diagram across all documents in one batch.
  const documents = [
    docs.readme,
    ...docs.sections.flatMap((section) => [section, ...section.supporting]),
  ];
  const origins = new Map();
  for (const document of documents) {
    const prepared = await prepareDiagrams(
      document,
      docsDir,
      diagramEngine === "mermaid" ? "off" : "auto",
    );
    document.body = prepared.body;
    origins.set(document.file, prepared.origins);
  }
  const nativeSources = new Map(
    documents.map((document) => [
      document.file,
      extractNativeSources(document.body),
    ]),
  );
  for (const [file, sources] of nativeSources)
    sources.forEach((source, i) =>
      parseNativeDiagram(source, {
        location: `${file}: archify fence ${i + 1}`,
      }),
    );
  const nativeResults = await renderNativeDiagrams(
    [...nativeSources.values()].flat(),
    {
      locations: [...nativeSources.entries()].flatMap(([file, sources]) =>
        sources.map((_, i) => `${file}: diagram ${i + 1}`),
      ),
    },
  );
  const nativeByDocument = new Map();
  const generatedFiles = new Map();
  let nativeCursor = 0;
  for (const document of documents) {
    const figures = [];
    for (const [i, source] of nativeSources.get(document.file).entries()) {
      const diagram = nativeResults[nativeCursor++];
      const origin = origins.get(document.file).get(source);
      if (origin?.reference) await checkPreview(origin.reference, diagram);
      diagram.id = createHash("sha256")
        .update(`${document.file}:${i}`)
        .digest("hex")
        .slice(0, 20);
      if (interactive) {
        generatedFiles.set(
          `diagrams/${diagram.id}/index.html`,
          buildNativeViewer(diagram),
        );
        generatedFiles.set(`diagrams/${diagram.id}/diagram.svg`, diagram.svg);
        if (origin?.mermaid)
          generatedFiles.set(
            `diagrams/${diagram.id}/source.md`,
            "```mermaid\n" + origin.mermaid + "\n```\n",
          );
        if (origin?.reference) {
          try {
            generatedFiles.set(
              `diagrams/${diagram.id}/source.md`,
              await readFile(origin.reference.companionPath, "utf8"),
            );
          } catch (error) {
            if (error.code !== "ENOENT") throw error;
          }
        }
        generatedFiles.set(`diagrams/${diagram.id}/source.json`, source + "\n");
        generatedFiles.set(
          `diagrams/${diagram.id}/provenance.json`,
          JSON.stringify(
            {
              document: document.file,
              fence: i + 1,
              hash: diagram.hash,
              renderer: "Archify 3.2.0",
            },
            null,
            2,
          ) + "\n",
        );
      }
      figures.push(nativeFigure(diagram, interactive));
    }
    nativeByDocument.set(document.file, figures);
  }
  const documentMermaid = new Map(
    documents.map((document) => [
      document.file,
      extractMermaidSources(document.body),
    ]),
  );
  const allMermaid = documents.flatMap((document) =>
    documentMermaid.get(document.file),
  );
  process.stdout.write(
    `arc42-snapshot: ${docs.sections.length} sections, ${allMermaid.length} mermaid diagram(s)\n`,
  );
  const svgs = await renderMermaid(allMermaid);

  // Distribute the rendered SVGs back to their documents.
  let cursor = 0;
  const take = (count) => {
    const slice = svgs.slice(cursor, cursor + count);
    cursor += count;
    return slice;
  };

  const revision = await gitRevision(docsDir);
  const sourceContext = await gitSourceContext(docsDir, flags["source-ref"]);
  const toSourcePath = (file) =>
    sourceContext
      ? relative(sourceContext.root, join(docsDir, file)).split(sep).join("/")
      : undefined;
  const readmeMermaid = documentMermaid.get(docs.readme.file);

  const readmeRendered = await renderMarkdown(docs.readme.body, {
    nativeDiagrams: nativeByDocument.get(docs.readme.file),
    fileToRoute,
    svgs: take(readmeMermaid.length),
    title: docs.readme.title,
    sourceContext,
    sourceFile: toSourcePath(docs.readme.file),
    documentPath: docs.readme.file,
    sourceRevision: revision,
    siteBase: flags["site-base"] ?? "/",
  });
  const sectionsRendered = [];
  for (let i = 0; i < docs.sections.length; i += 1) {
    const section = docs.sections[i];
    const rendered = await renderMarkdown(section.body, {
      nativeDiagrams: nativeByDocument.get(section.file),
      fileToRoute,
      svgs: take(documentMermaid.get(section.file).length),
      currentRoute: `#/section/${section.number}`,
      title: section.title,
      sourceContext,
      sourceFile: toSourcePath(section.file),
      documentPath: section.file,
      sourceRevision: revision,
      siteBase: flags["site-base"] ?? "/",
    });
    const supporting = [];
    for (const document of section.supporting) {
      const supportRendered = await renderMarkdown(document.body, {
        nativeDiagrams: nativeByDocument.get(document.file),
        fileToRoute,
        svgs: take(documentMermaid.get(document.file).length),
        currentRoute: document.route,
        title: document.title,
        sourceContext,
        sourceFile: toSourcePath(document.file),
        documentPath: document.file,
        sourceRevision: revision,
        siteBase: flags["site-base"] ?? "/",
      });
      supporting.push({
        route: document.route,
        relativeFile: document.relativeFile,
        title: document.title,
        description: document.description,
        html: supportRendered.html,
      });
    }
    sectionsRendered.push({
      number: section.number,
      title: section.title,
      description: section.description,
      html: rendered.html,
      supporting,
    });
  }

  const html = `${generatedMarker}\n${buildSnapshotHtml({
    interactive,
    readme: {
      title: docs.readme.title,
      description: docs.readme.description,
      html: readmeRendered.html,
    },
    sections: sectionsRendered,
    stackName,
    revision,
    brandImage: (
      await readFile(new URL("./arcshape-lockup.webp", import.meta.url))
    ).toString("base64"),
  })}`;

  if (interactive) {
    generatedFiles.set("index.html", html);
    await publishDirectory(outFile, docsDir, generatedFiles);
    process.stdout.write(
      `arc42-snapshot: interactive site written to ${outFile}\n`,
    );
    return;
  }

  await mkdir(dirname(outFile), { recursive: true });
  try {
    const existing = await readFile(outFile, "utf8");
    if (existing === html) {
      process.stdout.write(
        `arc42-snapshot: site is already up to date at ${outFile}\n`,
      );
      return;
    }
    if (!existing.includes(generatedMarker)) {
      throw new Diagnostic(
        `output already exists and is not an ArcShape-generated site: ${outFile}; choose another --out path or move the file`,
      );
    }
  } catch (error) {
    if (error instanceof Diagnostic) throw error;
    if (error.code !== "ENOENT") throw error;
  }
  await writeFile(outFile, html, "utf8");
  process.stdout.write(`arc42-snapshot: snapshot written to ${outFile}\n`);
}

main().catch((error) => {
  process.stderr.write(`arc42-snapshot: ${error.stack ?? error.message}\n`);
  process.exit(error instanceof Diagnostic ? 2 : 1);
});
