import { readFile, realpath, writeFile, stat } from "node:fs/promises";
import {
  resolve,
  dirname,
  relative,
  sep,
  extname,
  join,
  isAbsolute,
} from "node:path";
import { Marked } from "marked";
import {
  parseNativeDiagram,
  renderNativeDiagrams,
} from "./native-diagrams.mjs";
import { loadDocs } from "./loadDocs.mjs";

const marker = "<!-- Generated by ArcShape native preview. -->\n";
const comment = /^<!--\s*arcshape-diagram-source:\s*([^<>\r\n]+?)\s*-->\s*$/;
const inside = (root, path) => {
  const rel = relative(root, path);
  return rel !== ".." && !rel.startsWith(`..${sep}`) && !isAbsolute(rel);
};

async function localPath(root, document, href, extension, missing = false) {
  if (
    !href ||
    /[:\\?#%\x00-\x1f]/.test(href) ||
    href.startsWith("/") ||
    extname(href) !== extension
  )
    throw new Error(`${document}: expected a local ${extension} path: ${href}`);
  const candidate = resolve(root, dirname(document), href);
  if (!inside(root, candidate))
    throw new Error(`${document}: path escapes documentation root: ${href}`);
  // Validate the real parent before reading a target or writing a new preview.
  const parent = await realpath(dirname(candidate));
  if (!inside(root, parent))
    throw new Error(`${document}: symlink escapes documentation root: ${href}`);
  let actual;
  try {
    actual = await realpath(candidate);
  } catch (error) {
    if (!missing || error.code !== "ENOENT") throw error;
    actual = join(parent, candidate.slice(dirname(candidate).length + 1));
  }
  if (!inside(root, actual))
    throw new Error(`${document}: symlink escapes documentation root: ${href}`);
  try {
    const info = await stat(actual);
    if (
      !info.isFile() ||
      info.size > (extension === ".json" ? 256 * 1024 : 16 * 1024 * 1024)
    )
      throw new Error(
        `${document}: diagram reference must name a bounded regular file: ${href}`,
      );
  } catch (error) {
    if (!missing || error.code !== "ENOENT") throw error;
  }
  return actual;
}

export async function nativeReferences(body, { docsDir, document }) {
  const root = await realpath(docsDir);
  const marked = new Marked({ gfm: true });
  const tokens = marked.lexer(body);
  const references = [];
  let markers = 0;
  marked.walkTokens(tokens, (token) => {
    if (
      token.type === "html" &&
      token.text.includes("arcshape-diagram-source:")
    )
      markers++;
  });
  for (let i = 0; i < tokens.length; i++) {
    const token = tokens[i];
    if (
      token.type !== "html" ||
      !token.text.includes("arcshape-diagram-source:")
    )
      continue;
    const match = comment.exec(token.text);
    let previous = i - 1;
    while (previous >= 0 && tokens[previous].type === "space") previous--;
    const paragraph = tokens[previous];
    const image =
      paragraph?.type === "paragraph" &&
      paragraph.tokens?.length === 1 &&
      paragraph.tokens[0];
    if (!match || image?.type !== "image" || !image.text?.trim())
      throw new Error(
        `${document}: native source comment must immediately follow one titled SVG image`,
      );
    const sourcePath = await localPath(
      root,
      document,
      match[1].trim(),
      ".json",
    );
    const previewPath = await localPath(
      root,
      document,
      image.href,
      ".svg",
      true,
    );
    if (
      references.some(
        (r) => r.previewPath === previewPath || r.sourcePath === sourcePath,
      )
    )
      throw new Error(
        `${document}: ambiguous native source/preview association`,
      );
    const source = await readFile(sourcePath, "utf8");
    parseNativeDiagram(source, { location: `${document}: ${match[1]}` });
    references.push({
      source,
      sourcePath,
      previewPath,
      title: image.text,
      raw: tokens
        .slice(previous, i + 1)
        .map((t) => t.raw)
        .join(""),
    });
  }
  if (references.length !== markers)
    throw new Error(
      `${document}: native preview references must be standalone image/comment pairs`,
    );
  return references;
}

export const previewContent = (diagram) =>
  marker + diagram.svg.replace(/[\t ]+$/gm, "").trimEnd() + "\n";

export async function checkPreview(reference, diagram) {
  let existing;
  try {
    existing = await readFile(reference.previewPath, "utf8");
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  if (existing !== previewContent(diagram))
    throw new Error(
      `${reference.previewPath}: missing or stale native preview; run arcshape site previews --docs <docs-directory>`,
    );
}

export async function generatePreviews(docsDir, { check = false } = {}) {
  const docs = await loadDocs(docsDir);
  const documents = [
    docs.readme,
    ...docs.sections.flatMap((s) => [s, ...s.supporting]),
  ];
  const references = [];
  for (const document of documents)
    references.push(
      ...(await nativeReferences(document.body, {
        docsDir,
        document: document.file,
      })),
    );
  const previews = new Set();
  for (const reference of references) {
    if (previews.has(reference.previewPath))
      throw new Error(`duplicate native preview: ${reference.previewPath}`);
    previews.add(reference.previewPath);
  }
  const diagrams = await renderNativeDiagrams(references.map((r) => r.source));
  for (let i = 0; i < references.length; i++) {
    if (check) await checkPreview(references[i], diagrams[i]);
    else {
      let existing;
      try {
        existing = await readFile(references[i].previewPath, "utf8");
      } catch (error) {
        if (error.code !== "ENOENT") throw error;
      }
      if (existing !== undefined && !existing.startsWith(marker))
        throw new Error(
          `refusing to overwrite an authored SVG: ${references[i].previewPath}`,
        );
      await writeFile(references[i].previewPath, previewContent(diagrams[i]));
    }
  }
  return references.length;
}
